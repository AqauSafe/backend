"""Generate broker ACLs and synchronise provisioned device passwords."""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from apps.devices.models import Device
from apps.devices.provisioning import device_mqtt_password
from integrations.mqtt.topics import (
    command_ack_topic,
    commands_topic,
    config_ack_topic,
    config_topic,
    events_topic,
    heartbeat_topic,
    status_topic,
    telemetry_topic,
)


class Command(BaseCommand):
    help = "Write per-device ACLs and update the Mosquitto password file."

    def add_arguments(self, parser):
        parser.add_argument(
            "--acl-file",
            default=str(settings.BASE_DIR / "mosquitto/config/acl.generated"),
        )
        parser.add_argument(
            "--passwd-file",
            default=str(settings.BASE_DIR / "mosquitto/config/passwd"),
        )
        parser.add_argument(
            "--skip-passwords",
            action="store_true",
            help="Write ACLs only; useful when mosquitto_passwd is unavailable.",
        )

    def handle(self, *args, **options):
        devices = list(Device.objects.exclude(secret_encrypted="").select_related("farm", "pond"))
        acl_path = Path(options["acl_file"])
        acl_path.parent.mkdir(parents=True, exist_ok=True)
        acl_path.write_text(self._render_acl(devices))
        self.stdout.write(self.style.SUCCESS(f"Wrote ACLs for {len(devices)} device(s)."))

        if options["skip_passwords"] or not devices:
            return
        binary = shutil.which("mosquitto_passwd")
        if binary is None:
            raise CommandError(
                "mosquitto_passwd is not installed. Use --skip-passwords or run through "
                "the Mosquitto container."
            )
        passwd_path = Path(options["passwd_file"])
        passwd_path.parent.mkdir(parents=True, exist_ok=True)
        if settings.MQTT_USERNAME and settings.MQTT_PASSWORD:
            self._set_password(binary, passwd_path, settings.MQTT_USERNAME, settings.MQTT_PASSWORD)
        for device in devices:
            self._set_password(binary, passwd_path, device.device_id, device_mqtt_password(device))
        self.stdout.write(self.style.SUCCESS(f"Updated {passwd_path}."))

    def _render_acl(self, devices) -> str:
        lines = [
            "# Generated by sync_mqtt_credentials. Do not edit by hand.",
            "",
            f"user {settings.MQTT_USERNAME}",
            f"topic readwrite {settings.MQTT_TOPIC_PREFIX}/#",
            "",
        ]
        for device in devices:
            device_id = device.device_id
            lines.extend(
                [
                    f"user {device_id}",
                    f"topic write {telemetry_topic(device_id)}",
                    f"topic write {heartbeat_topic(device_id)}",
                    f"topic write {events_topic(device_id)}",
                    f"topic write {status_topic(device_id)}",
                    f"topic read {commands_topic(device_id)}",
                    f"topic write {command_ack_topic(device_id)}",
                    f"topic read {config_topic(device_id)}",
                    f"topic write {config_ack_topic(device_id)}",
                    "",
                ]
            )
        return "\n".join(lines)

    def _set_password(self, binary: str, path: Path, username: str, password: str) -> None:
        subprocess.run(
            [binary, "-b", str(path), username, password],
            check=True,
            capture_output=True,
            text=True,
        )
